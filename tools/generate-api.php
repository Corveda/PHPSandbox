<?php

declare(strict_types=1);

require dirname(__DIR__) . '/vendor/autoload.php';

function apiType(?ReflectionType $type): string
{
    if($type === null){
        return '';
    }
    if($type instanceof ReflectionNamedType){
        return ($type->allowsNull() && $type->getName() !== 'mixed' && $type->getName() !== 'null' ? '?' : '')
            . $type->getName();
    }
    $separator = $type instanceof ReflectionIntersectionType ? '&' : '|';
    return implode($separator, array_map(apiType(...), $type->getTypes()));
}

function apiSummary(Reflector $reflector): string
{
    if(!method_exists($reflector, 'getDocComment') || !($comment = $reflector->getDocComment())){
        return '';
    }
    $lines = preg_split('/\R/', $comment) ?: [];
    foreach($lines as $line){
        $line = trim($line, " \t\n\r\0\x0B/*");
        if($line !== '' && $line[0] !== '@'){
            return str_replace('|', '\\|', $line);
        }
    }
    return '';
}

function apiSignature(ReflectionMethod $method): string
{
    $parameters = [];
    foreach($method->getParameters() as $parameter){
        $part = apiType($parameter->getType());
        $part .= ($part !== '' ? ' ' : '') . ($parameter->isPassedByReference() ? '&' : '');
        $part .= $parameter->isVariadic() ? '...' : '';
        $part .= '$' . $parameter->getName();
        if($parameter->isDefaultValueAvailable() && !$parameter->isVariadic()){
            $part .= ' = ' . var_export($parameter->getDefaultValue(), true);
        }
        $parameters[] = $part;
    }
    return ($method->isStatic() ? 'static ' : '') . $method->getName() . '(' . implode(', ', $parameters) . ')'
        . (($return = apiType($method->getReturnType())) !== '' ? ': ' . $return : '');
}

$classes = [
    PHPSandbox\PHPSandbox::class,
    PHPSandbox\Error::class,
    PHPSandbox\SandboxedString::class,
];
$lines = [
    '# Generated API reference',
    '',
    '<!-- Generated by tools/generate-api.php; do not edit directly. -->',
    '',
    'This signature index is generated from the PHP 8.1–8.5 source. See [API guide](api.md) for semantics and [security model](security.md) for trust boundaries.',
    '',
];

foreach($classes as $className){
    $class = new ReflectionClass($className);
    $lines[] = '## `' . $class->getName() . '`';
    $lines[] = '';
    if(($summary = apiSummary($class)) !== ''){
        $lines[] = $summary;
        $lines[] = '';
    }
    $lines[] = '### Constants';
    $lines[] = '';
    foreach($class->getReflectionConstants(ReflectionClassConstant::IS_PUBLIC) as $constant){
        if($constant->getDeclaringClass()->getName() === $class->getName()){
            $lines[] = '- `' . $constant->getName() . '`';
        }
    }
    $lines[] = '';
    $lines[] = '### Properties';
    $lines[] = '';
    $lines[] = '| Signature | Description |';
    $lines[] = '| --- | --- |';
    foreach($class->getProperties(ReflectionProperty::IS_PUBLIC) as $property){
        if($property->getDeclaringClass()->getName() === $class->getName()){
            $signature = ($property->isStatic() ? 'static ' : '') . apiType($property->getType()) . ' $' . $property->getName();
            $lines[] = '| `' . str_replace('|', '\\|', trim($signature)) . '` | ' . apiSummary($property) . ' |';
        }
    }
    $lines[] = '';
    $lines[] = '### Methods';
    $lines[] = '';
    $lines[] = '| Signature | Description |';
    $lines[] = '| --- | --- |';
    foreach($class->getMethods(ReflectionMethod::IS_PUBLIC) as $method){
        if($method->getDeclaringClass()->getName() === $class->getName()){
            $lines[] = '| `' . str_replace('|', '\\|', apiSignature($method)) . '` | ' . apiSummary($method) . ' |';
        }
    }
    $lines[] = '';
}

$target = dirname(__DIR__) . '/documentation/api-reference.md';
if(file_put_contents($target, implode(PHP_EOL, $lines) . PHP_EOL) === false){
    fwrite(STDERR, "Could not write $target\n");
    exit(1);
}
fwrite(STDOUT, "Generated $target\n");
