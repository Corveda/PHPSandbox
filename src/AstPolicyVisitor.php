    public function __construct(private PHPSandbox $sandbox)
    {
    }

    public function enterNode(Node $node)
    {
        if (!isset(self::SUPPORTED[$node::class])) {
            $this->sandbox->validationError(
                'Sandboxed code contains an AST node unsupported by this policy version: ' . $node->getType(),
                Error::UNKNOWN_NODE_ERROR,
                $node,
                $node::class
            );
        }
        return null;
    }

    /** @return array<class-string<Node>, true> */
    public static function supportedNodes(): array
    {
        return self::SUPPORTED;
    }
